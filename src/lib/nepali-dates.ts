// 2000-01-01 BS == 1943-04-14 AD (UTC midnight).
const REF_AD_MS = Date.UTC(1943, 3, 14);
const DAY_MS = 86_400_000;

function startOfDayMs(d: Date): number {
  return Date.UTC(d.getFullYear(), d.getMonth(), d.getDate());
}

export function bsMonthLength(y: number, m: number): number | null {
  const row = BS_DATA[y];
  if (!row || m < 1 || m > 12) return null;
  return row[m - 1] ?? null;
}

/** Gregorian date -> Bikram Sambat. Null outside BS 2000-2090. */
export function adToBs(date: Date): BsDate | null {
  const diff = Math.round((startOfDayMs(date) - REF_AD_MS) / DAY_MS);
  if (diff < 0) return null;
  let remaining = diff;
  for (let y = BS_MIN_YEAR; y <= BS_MAX_YEAR; y++) {
    const row = BS_DATA[y];
    if (!row) return null;
    const yearLen = row.reduce((a, b) => a + b, 0);
    if (remaining < yearLen) {
      for (let m = 0; m < 12; m++) {
        const ml = row[m]!;
        if (remaining < ml) return { y, m: m + 1, d: remaining + 1 };
        remaining -= ml;
      }
      return null;
    }
    remaining -= yearLen;
  }
  return null;
}

/** Bikram Sambat -> Gregorian date (local midnight). Null when out of range. */
export function bsToAd(y: number, m: number, d: number): Date | null {
  if (y < BS_MIN_YEAR || y > BS_MAX_YEAR || m < 1 || m > 12) return null;
  const ml = bsMonthLength(y, m);
  if (!ml || d < 1 || d > ml) return null;
  let days = d - 1;
  for (let yy = BS_MIN_YEAR; yy < y; yy++) {
    const row = BS_DATA[yy];
    if (!row) return null;
    days += row.reduce((a, b) => a + b, 0);
  }
  const row = BS_DATA[y];
  if (!row) return null;
  for (let mm = 0; mm < m - 1; mm++) days += row[mm]!;
  return new Date(REF_AD_MS + days * DAY_MS);
}

export function todayBs(): BsDate | null {
  return adToBs(new Date());
}

export function formatBs(bs: BsDate, opts?: { nepali?: boolean }): string {
  const months = opts?.nepali ? BS_MONTHS_NE : BS_MONTHS_EN;
  return `${months[bs.m - 1]} ${bs.d}, ${bs.y}`;
}

/** "2026-09-12" style key for grouping events by Gregorian day. */
export function adKey(d: Date): string {
  const p = (n: number) => String(n).padStart(2, "0");
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}

/** Parse feed dates ("YYYY-MM-DD" or with time) into a local Date. Null when unknown. */
export function parseFeedDate(value: unknown): Date | null {
  if (value === null || value === undefined || value === "") return null;
  const raw = String(value).trim();
  if (!raw || /^(null|undefined|-|n\/?a)$/i.test(raw)) return null;
  const d = new Date(raw.includes("T") ? raw : raw.replace(" ", "T"));
  if (Number.isNaN(d.getTime())) return null;
  return new Date(d.getFullYear(), d.getMonth(), d.getDate());
}
